// Builds apps/api/infra/free-stack.json (the one CloudFormation template for dev and qa, deployed twice) from infra/tables.yaml.
/**
 * M30 (specs/032-m30-four-environments, research D1 option a). Run `npx tsx infra/build-free-stack.ts` in apps/api to rewrite
 * free-stack.json; test/free-stack.test.ts fails when the committed file differs from a fresh build (not in package.json on purpose).
 *
 * - Parameter `Env` is `dev` or `qa`. Tables are PROVISIONED so the pair stays inside the free account's 25 RCU / 25 WCU:
 *   main 3/3, events 1/1, cache 1/1, every GSI 1/1 => 12/12 per env, 24/24 for both. No on-demand, no auto scaling, no PITR.
 * - The API runs on Vercel, so there is no API Lambda. The worker Lambda (placeholder code, role from `WorkerRoleArn`), its
 *   3-day log group, the Stream mapping and the two schedules reproduce the staging drain (D1).
 * - One managed policy for the IAM user the Vercel API signs in as: data actions only, on exactly these three tables and their indexes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseTemplate } from '../src/db/ddb/schema.ts';
import { OUTBOX_FILTER } from './build-stack.ts';

const HERE = fileURLToPath(new URL('.', import.meta.url));
type Json = Record<string, any>;

const sub = (s: string) => ({ 'Fn::Sub': s });
const ref = (n: string) => ({ Ref: n });
const getAtt = (n: string, a: string) => ({ 'Fn::GetAtt': [n, a] });

const PLACEHOLDER = `exports.handler = async () => ({ statusCode: 503, headers: { 'content-type': 'application/json' }, body: JSON.stringify({ error: 'not deployed yet' }) });`;

/** Provisioned throughput (RCU = WCU) per table and per index. */
export const TABLE_UNITS = { main: 3, events: 1, cache: 1 } as const;
export const INDEX_UNITS = 1;

/** The DynamoDB data actions the API uses (src/db/ddb, src/jobs: Scan in charts.ts and cache-sweep.ts). No table management.
 *  IAM has no TransactGetItems / TransactWriteItems action (cfn-lint W3037): a transaction is authorised by the item actions of its parts, so
 *  GetItem, PutItem, UpdateItem, DeleteItem and ConditionCheckItem cover TransactGetItems and TransactWriteItems. */
export const API_ACTIONS = [
  'dynamodb:GetItem', 'dynamodb:PutItem', 'dynamodb:UpdateItem', 'dynamodb:DeleteItem', 'dynamodb:Query', 'dynamodb:Scan',
  'dynamodb:BatchGetItem', 'dynamodb:BatchWriteItem', 'dynamodb:ConditionCheckItem', 'dynamodb:DescribeTable',
];

function tables(): Json {
  const src = parseTemplate(readFileSync(`${HERE}tables.yaml`, 'utf8')).Resources;
  const byName: Record<string, { id: string; role: 'main' | 'events' | 'cache' }> = { 'sm-main': { id: 'Main', role: 'main' }, 'sm-events': { id: 'Events', role: 'events' }, 'sm-cache': { id: 'Cache', role: 'cache' } };
  const out: Json = {};
  let previous: string | undefined;
  for (const res of Object.values(src)) {
    const p = structuredClone(res.Properties) as Json;
    const { id, role } = byName[p['TableName'] as string]!;
    p['TableName'] = sub(`\${Env}-${role}`);
    p['BillingMode'] = 'PROVISIONED';
    p['ProvisionedThroughput'] = { ReadCapacityUnits: TABLE_UNITS[role], WriteCapacityUnits: TABLE_UNITS[role] };
    p['DeletionProtectionEnabled'] = false;
    p['PointInTimeRecoverySpecification'] = { PointInTimeRecoveryEnabled: false };
    for (const g of (p['GlobalSecondaryIndexes'] ?? []) as Json[]) g['ProvisionedThroughput'] = { ReadCapacityUnits: INDEX_UNITS, WriteCapacityUnits: INDEX_UNITS };
    out[id] = {
      Type: 'AWS::DynamoDB::Table',
      ...(previous ? { DependsOn: previous } : {}),
      DeletionPolicy: 'Retain',
      UpdateReplacePolicy: 'Retain',
      Properties: p,
    };
    previous = id;
  }
  return out;
}

export function buildFreeStack(): Json {
  const tableArn = (r: string) => getAtt(r, 'Arn');
  return {
    AWSTemplateFormatVersion: '2010-09-09',
    Description: 'SocialMorning free environments (dev, qa): provisioned DynamoDB tables inside the free 25/25 units, the outbox worker Lambda, its Stream mapping and schedules, and the IAM policy for the Vercel API user. Deploy once per Env. Generated by apps/api/infra/build-free-stack.ts — do not edit by hand.',
    Parameters: {
      Env: { Type: 'String', AllowedValues: ['dev', 'qa'], Description: 'dev or qa. Prefixes every resource name.' },
      WorkerRoleArn: { Type: 'String', Description: 'The Lambda execution role the owner created for the worker (<Env>-worker-role).' },
      SchedulerRoleArn: { Type: 'String', Description: 'The EventBridge Scheduler role the owner created (<Env>-scheduler-role).' },
    },
    Resources: {
      ...tables(),
      WorkerLogs: { Type: 'AWS::Logs::LogGroup', DeletionPolicy: 'Delete', Properties: { LogGroupName: sub('/aws/lambda/${Env}-worker'), RetentionInDays: 3 } },
      Worker: {
        Type: 'AWS::Lambda::Function',
        DependsOn: 'WorkerLogs',
        Properties: {
          FunctionName: sub('${Env}-worker'),
          Runtime: 'nodejs22.x', Architectures: ['arm64'], MemorySize: 512, Timeout: 60,
          Handler: 'index.handler', Role: ref('WorkerRoleArn'),
          Environment: { Variables: { APP_ENV: ref('Env'), DATA_BACKEND: 'ddb', DDB_TABLE_PREFIX: ref('Env'), SECRETS_PATH: sub('/${Env}/api/'), SECRETS_REQUIRED: 'JOB_TOKEN' } },
          Code: { ZipFile: PLACEHOLDER },
        },
      },
      OutboxTrigger: {
        Type: 'AWS::Lambda::EventSourceMapping',
        Properties: {
          FunctionName: ref('Worker'),
          EventSourceArn: getAtt('Main', 'StreamArn'),
          StartingPosition: 'LATEST',
          BatchSize: 50,
          ParallelizationFactor: 1,
          MaximumBatchingWindowInSeconds: 1,
          MaximumRetryAttempts: 3,
          MaximumRecordAgeInSeconds: 3600,
          BisectBatchOnFunctionError: true,
          FunctionResponseTypes: ['ReportBatchItemFailures'],
          FilterCriteria: { Filters: [{ Pattern: JSON.stringify(OUTBOX_FILTER) }] },
        },
      },
      DrainEveryMinute: {
        Type: 'AWS::Scheduler::Schedule',
        Properties: {
          Name: sub('${Env}-outbox-drain'), ScheduleExpression: 'rate(1 minute)', FlexibleTimeWindow: { Mode: 'OFF' },
          Target: { Arn: getAtt('Worker', 'Arn'), RoleArn: ref('SchedulerRoleArn'), Input: '{"kind":"drain"}', RetryPolicy: { MaximumRetryAttempts: 2, MaximumEventAgeInSeconds: 3600 } },
        },
      },
      JobsHourly: {
        Type: 'AWS::Scheduler::Schedule',
        Properties: {
          Name: sub('${Env}-jobs-hourly'), ScheduleExpression: 'rate(1 hour)', FlexibleTimeWindow: { Mode: 'OFF' },
          Target: { Arn: getAtt('Worker', 'Arn'), RoleArn: ref('SchedulerRoleArn'), Input: '{"kind":"jobs"}', RetryPolicy: { MaximumRetryAttempts: 2, MaximumEventAgeInSeconds: 3600 } },
        },
      },
      VercelApiPolicy: {
        Type: 'AWS::IAM::ManagedPolicy',
        Properties: {
          ManagedPolicyName: sub('${Env}-vercel-api-ddb'),
          Description: 'Data access for the Vercel-hosted API of this environment: the three tables and their indexes, no table management.',
          PolicyDocument: {
            Version: '2012-10-17',
            Statement: [{
              Sid: 'TablesAndIndexes', Effect: 'Allow', Action: API_ACTIONS,
              Resource: [tableArn('Main'), tableArn('Events'), tableArn('Cache'), sub('${Main.Arn}/index/*'), sub('${Events.Arn}/index/*'), sub('${Cache.Arn}/index/*')],
            }],
          },
        },
      },
    },
    Outputs: {
      MainTableName: { Value: ref('Main') }, EventsTableName: { Value: ref('Events') }, CacheTableName: { Value: ref('Cache') },
      MainTableArn: { Value: tableArn('Main') }, EventsTableArn: { Value: tableArn('Events') }, CacheTableArn: { Value: tableArn('Cache') },
      MainStreamArn: { Value: getAtt('Main', 'StreamArn') },
      WorkerName: { Value: ref('Worker') },
      VercelApiPolicyArn: { Description: 'Attach this to the IAM user whose access key the Vercel API project uses.', Value: ref('VercelApiPolicy') },
    },
  };
}

export const freeStackText = (): string => `${JSON.stringify(buildFreeStack(), null, 2)}\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(`${HERE}free-stack.json`, freeStackText());
  console.log('wrote apps/api/infra/free-stack.json');
}
